/**
 * Bulk-mail detection from RFC header fields.
 *
 * Lets a mailbox be triaged (newsletter vs automated notification vs personal
 * mail) from headers alone — deterministic, and cheap enough to run over a
 * whole page of results in a single IMAP fetch.
 */

import type { BulkKind, BulkSignal } from '../types/index.js';

/**
 * Header fields worth fetching for classification. Kept deliberately short:
 * every field here is pulled for every message in a listing.
 */
export const BULK_HEADER_FIELDS = [
  'list-unsubscribe',
  'list-unsubscribe-post',
  'list-id',
  'precedence',
  'auto-submitted',
];

/** `Precedence:` values that mark mail as machine-originated rather than a list. */
const AUTOMATED_PRECEDENCE = new Set(['bulk', 'junk', 'auto_reply']);

/**
 * Parse a raw header block into lowercased keys.
 *
 * Unfolds continuation lines per RFC 5322 §2.2.3 — a folded `List-Unsubscribe`
 * carrying both an https and a mailto URI is common, and naive line splitting
 * silently truncates it.
 */
export function parseHeaderBlock(raw: string): Record<string, string> {
  const allLines = raw.split(/\r?\n/);
  // A blank line ends the header block; everything after it is body.
  const blankIndex = allLines.findIndex((line) => line.length === 0);
  const lines = blankIndex >= 0 ? allLines.slice(0, blankIndex) : allLines;

  // Unfold: a line starting with whitespace continues the field above it.
  const fields = lines.reduce<string[]>((acc, line) => {
    if (/^[ \t]/.test(line) && acc.length > 0) {
      acc[acc.length - 1] = `${acc[acc.length - 1]} ${line.trim()}`.trim();
    } else {
      acc.push(line);
    }
    return acc;
  }, []);

  return Object.fromEntries(
    fields
      .map((line) => {
        const colonIndex = line.indexOf(':');
        if (colonIndex <= 0) {
          return null;
        }
        return [
          line.slice(0, colonIndex).trim().toLowerCase(),
          line.slice(colonIndex + 1).trim(),
        ] as const;
      })
      .filter((entry): entry is readonly [string, string] => entry !== null),
  );
}

/** Pick the most actionable unsubscribe URI, preferring https over mailto. */
function pickUnsubscribeUri(value: string): string | undefined {
  const uris = [...value.matchAll(/<([^>]+)>/g)].map((m) => m[1]?.trim()).filter(Boolean);
  const candidates = uris.length > 0 ? uris : [value.trim()];
  return (
    candidates.find((u) => u?.startsWith('https://')) ??
    candidates.find((u) => u?.startsWith('http://')) ??
    candidates.find((u) => u?.startsWith('mailto:')) ??
    candidates[0]
  );
}

/** Strip the angle brackets List-Id wraps its identifier in. */
function cleanListId(value: string): string {
  const bracketed = /<([^>]+)>/.exec(value);
  return (bracketed?.[1] ?? value).trim();
}

/**
 * Classify a message from its headers.
 *
 * Returns `undefined` for ordinary person-to-person mail, so callers can stay
 * silent rather than labelling every message.
 */
export function classifyBulk(headers: Record<string, string>): BulkSignal | undefined {
  const unsubscribeRaw = headers['list-unsubscribe'];
  const listIdRaw = headers['list-id'];
  const precedence = headers.precedence?.trim().toLowerCase();
  const autoSubmitted = headers['auto-submitted']?.trim().toLowerCase();

  // RFC 3834: anything but "no" means the message was generated by software.
  const isAutomated =
    (autoSubmitted !== undefined && autoSubmitted !== 'no') ||
    (precedence !== undefined && AUTOMATED_PRECEDENCE.has(precedence));

  const isList = unsubscribeRaw !== undefined || listIdRaw !== undefined || precedence === 'list';

  if (!isList && !isAutomated) {
    return undefined;
  }

  // A list wins over the automated marker: bulk senders routinely set both, and
  // "newsletter" is the more actionable of the two for triage.
  const kind: BulkKind = isList ? 'newsletter' : 'automated';

  return {
    kind,
    listId: listIdRaw ? cleanListId(listIdRaw) : undefined,
    unsubscribe: unsubscribeRaw ? pickUnsubscribeUri(unsubscribeRaw) : undefined,
    // RFC 8058: presence of List-Unsubscribe-Post means one-click works.
    oneClick: headers['list-unsubscribe-post'] !== undefined,
  };
}
